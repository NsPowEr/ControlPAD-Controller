import AppKit

/// Traduzione fra i codici tasto virtuali di macOS (quelli che arrivano in
/// `NSEvent.keyCode`) e gli usage HID che il ControlPad si aspetta.
///
/// Sono due numerazioni scorrelate: macOS numera per posizione storica sulla
/// tastiera Apple, l'USB HID per la tabella standard. Senza questa tabella una
/// macro registrata premendo "A" finirebbe sul pad come un tasto a caso.
enum MacKeyCodes {
    static let toHID: [UInt16: UInt8] = [
        // lettere
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08,
        0x03: 0x09, 0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C, 0x26: 0x0D,
        0x28: 0x0E, 0x25: 0x0F, 0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12,
        0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15, 0x01: 0x16, 0x11: 0x17,
        0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B, 0x10: 0x1C,
        0x06: 0x1D,
        // cifre
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22,
        0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,
        // controllo e punteggiatura
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31,
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37,
        0x2C: 0x38, 0x39: 0x39, 0x0A: 0x64,
        // funzione
        0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E,
        0x61: 0x3F, 0x62: 0x40, 0x64: 0x41, 0x65: 0x42, 0x6D: 0x43,
        0x67: 0x44, 0x6F: 0x45,
        // navigazione
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D,
        0x79: 0x4E, 0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52,
        // tastierino
        0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C, 0x57: 0x5D,
        0x58: 0x5E, 0x59: 0x5F, 0x5B: 0x60, 0x5C: 0x61, 0x52: 0x62,
        0x41: 0x63, 0x4B: 0x54, 0x43: 0x55, 0x4E: 0x56, 0x45: 0x57,
        0x4C: 0x58,
    ]

    /// I modificatori non producono keyDown/keyUp ma `flagsChanged`, e vanno
    /// riconosciuti dal codice tasto perché lo stesso flag (per esempio
    /// Shift) può venire da sinistra o da destra.
    static let modifiers: [UInt16: UInt8] = [
        0x38: 0xE1, 0x3C: 0xE5,   // Shift sinistro / destro
        0x3B: 0xE0, 0x3E: 0xE4,   // Control
        0x3A: 0xE2, 0x3D: 0xE6,   // Option → Alt
        0x37: 0xE3, 0x36: 0xE7,   // Command → GUI
    ]

    static func hidUsage(for keyCode: UInt16) -> UInt8? {
        modifiers[keyCode] ?? toHID[keyCode]
    }
}
